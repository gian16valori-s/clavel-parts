-- BORRADOR: no ejecutar en Supabase hasta revisar el esquema desplegado y las politicas.
-- Preparado a partir de los metadatos de Supabase compartidos por el usuario:
-- vendedores.id, versiones.id y productos.id son integer NOT NULL.
-- Las FK a esas tablas usan integer; los IDs de las tablas nuevas son bigint.
--
-- Modelo inicial:
--   vendedor -> vehiculo donante -> pieza usada -> producto del catalogo
-- La version del catalogo es obligatoria. Procedencia no implica compatibilidad.
-- Cada pieza usada referencia un unico producto; el producto se reutiliza en ambos
-- recorridos, el catalogo general y el inventario del donante.
-- Cerrar un donante no retira sus piezas ya publicadas; cada pieza conserva su estado.
-- El vendedor se habilita manualmente insertando su perfil en perfiles_desarmadero
-- despues de revisar la solicitud recibida por email.
-- Para suspender el acceso, despublicar primero las piezas/productos y quitar su
-- perfil de esa tabla; no se borra ni modifica el historial de los donantes.
--
-- Estas politicas habilitan lectura publica solo para piezas publicadas y sus
-- donantes/fotos. Las escrituras quedan limitadas al vendedor autenticado.
-- Revisar y probar el acceso por rol en un proyecto de prueba antes de ejecutar.
-- Este borrador no incluye documentos privados ni configura Storage; el formulario
-- de solicitud envia los documentos por correo y no los almacena en Supabase.

create table if not exists public.vehiculos_donantes (
  id bigint generated by default as identity primary key,
  vendedor_id integer not null,
  version_id integer not null,
  estado text not null default 'en_preparacion',
  descripcion text,
  created_at timestamptz not null default now(),
  constraint vehiculos_donantes_estado_check
    check (estado in ('en_preparacion', 'en_desarme', 'cerrado')),
  constraint vehiculos_donantes_vendedor_fk
    foreign key (vendedor_id)
    references public.vendedores(id)
    on delete restrict,
  constraint vehiculos_donantes_version_fk
    foreign key (version_id)
    references public.versiones(id)
    on delete restrict,
  constraint vehiculos_donantes_id_vendedor_unico
    unique (id, vendedor_id)
);

create table if not exists public.perfiles_desarmadero (
  vendedor_id integer primary key references public.vendedores(id) on delete restrict,
  nombre text not null,
  localidad text,
  provincia text,
  habilitado_en timestamptz not null default now()
);

create unique index if not exists idx_productos_id_vendedor_unique
  on public.productos(id, vendedor_id);

create table if not exists public.piezas_usadas (
  id bigint generated by default as identity primary key,
  vehiculo_donante_id bigint not null,
  vendedor_id integer not null,
  producto_id integer not null unique,
  estado text not null default 'borrador',
  created_at timestamptz not null default now(),
  constraint piezas_usadas_estado_check
    check (estado in ('borrador', 'publicada', 'reservada', 'vendida', 'retirada')),
  constraint piezas_usadas_donante_fk
    foreign key (vehiculo_donante_id)
    references public.vehiculos_donantes(id, vendedor_id)
    on delete restrict,
  constraint piezas_usadas_producto_fk
    foreign key (producto_id, vendedor_id)
    references public.productos(id, vendedor_id)
    on delete cascade
);

create table if not exists public.fotos_vehiculo_donante (
  id bigint generated by default as identity primary key,
  vehiculo_donante_id bigint not null,
  url text not null,
  orden smallint not null default 1,
  created_at timestamptz not null default now(),
  constraint fotos_donante_vehiculo_fk
    foreign key (vehiculo_donante_id)
    references public.vehiculos_donantes(id)
    on delete cascade,
  constraint fotos_donante_orden_unico
    unique (vehiculo_donante_id, orden)
);

create index if not exists idx_vehiculos_donantes_vendedor
  on public.vehiculos_donantes(vendedor_id);

create index if not exists idx_vehiculos_donantes_version
  on public.vehiculos_donantes(version_id);

create index if not exists idx_piezas_usadas_donante
  on public.piezas_usadas(vehiculo_donante_id);

create index if not exists idx_fotos_donante_vehiculo_orden
  on public.fotos_vehiculo_donante(vehiculo_donante_id, orden);

alter table public.vehiculos_donantes enable row level security;
alter table public.piezas_usadas enable row level security;
alter table public.fotos_vehiculo_donante enable row level security;
alter table public.perfiles_desarmadero enable row level security;

revoke all on public.vehiculos_donantes, public.piezas_usadas, public.fotos_vehiculo_donante, public.perfiles_desarmadero
  from public, anon, authenticated;

grant select on public.vehiculos_donantes, public.piezas_usadas, public.fotos_vehiculo_donante
  to anon, authenticated;
grant insert, update on public.vehiculos_donantes, public.piezas_usadas, public.fotos_vehiculo_donante
  to authenticated;
grant select on public.perfiles_desarmadero to anon, authenticated;

grant usage, select on sequence
  public.vehiculos_donantes_id_seq,
  public.piezas_usadas_id_seq,
  public.fotos_vehiculo_donante_id_seq
  to authenticated;

create policy "Public can read published used parts"
  on public.piezas_usadas
  for select
  to anon, authenticated
  using (
    estado = 'publicada'
    and exists (
      select 1
      from public.perfiles_desarmadero pd
      where pd.vendedor_id = piezas_usadas.vendedor_id
    )
  );

create policy "Sellers can read their used parts"
  on public.piezas_usadas
  for select
  to authenticated
  using (
    exists (
      select 1
      from public.vendedores v
      where v.id = piezas_usadas.vendedor_id
        and v.auth_user_id = (select auth.uid())
        and exists (
          select 1
          from public.perfiles_desarmadero pd
          where pd.vendedor_id = v.id
        )
    )
  );

